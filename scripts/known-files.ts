// Writes src/core/known-files.ts: the checksums of every file of every version of the built-in packages (EdgeTX SD
// content and sounds from 2.12 on, the projects and the ELRS script), so the app can tell which version a card holds.
// Run it before every release: node scripts/known-files.ts [download folder]
// Versions already in known-files.ts are taken from there; only new versions, or files added to an old one (a new
// voice), are downloaded. GITHUB_TOKEN, when set, raises GitHub's limit of 60 requests an hour.
import { createWriteStream, existsSync } from 'node:fs';
import { mkdir, rename, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import type { ReadableStream } from 'node:stream/web';
import { listReleases, type Release } from '../src/core/github.ts';
import { KNOWN_FILES } from '../src/core/known-files.ts';
import { knownVersionIn, packKnown, SOUND_ZIP, tooOld, unpackKnown, type KnownCatalog, type KnownVersion } from '../src/core/known.ts';
import { DEFAULT_SOURCES, type Source } from '../src/core/settings.ts';

const cache = process.argv[2] ?? join(tmpdir(), 'radio-manager-known-files');
const token = process.env.GITHUB_TOKEN;
const fetchFn: typeof fetch = (url, init) =>
  fetch(url, token && String(url).startsWith('https://api.github.com/') ? { ...init, headers: { ...init?.headers, Authorization: `Bearer ${token}` } } : init);

// Every file of a version, unlike the app, which only fetches what its radios use.
function files(source: Source, r: Release): { name: string; url: string; size?: number }[] {
  const assets = r.assets.filter((a) =>
    source.kind === 'sdcard' ? a.name.endsWith('.zip') || a.name === 'sdcard.json' : source.file ? a.name === source.file.asset : a.name.endsWith('.zip'),
  );
  if (assets.length > 0 || source.kind !== 'project' || source.file) return assets;
  return [{ name: `${source.repo.split('/')[1]}-${r.tag}.zip`, url: r.zipball }];
}

async function fetchTo(url: string, path: string): Promise<void> {
  const res = await fetchFn(url, { headers: { 'User-Agent': 'edgetx-radio-manager' } });
  if (!res.ok || !res.body) throw new Error(`${url}: ${res.status}`);
  await pipeline(Readable.fromWeb(res.body as ReadableStream<Uint8Array>), createWriteStream(`${path}.part`));
  await rename(`${path}.part`, path);
}

// The variant a file of a release becomes ('' for projects); undefined for files that aren't one (sdcard.json).
function variantOf(source: Source, name: string): string | undefined {
  if (source.kind === 'sdcard') return name.endsWith('.zip') ? name.slice(0, -4) : undefined;
  if (source.kind === 'sounds') return name.match(SOUND_ZIP)?.[1];
  return '';
}

const catalog: KnownCatalog = {};
let downloaded = 0;
for (const source of DEFAULT_SOURCES.filter((s) => s.kind !== 'firmware')) {
  const releases = (await listReleases(source.repo, fetchFn)).filter((r) => !tooOld(source, r.tag));
  const stored = new Map((KNOWN_FILES[source.name] ? unpackKnown(KNOWN_FILES[source.name]) : []).map((v) => [v.tag, v]));
  const versions: KnownVersion[] = [];
  for (const r of releases) {
    const old = stored.get(r.tag);
    // only what the stored checksums lack: a new version, or a file added to an old one
    const wanted = files(source, r).filter((f) => {
      const variant = variantOf(source, f.name);
      return !old || (variant === undefined ? !old.boards : !old.variants.has(variant));
    });
    if (wanted.length === 0) {
      if (old) versions.push(old);
      continue;
    }
    const dir = join(cache, source.name, r.tag);
    await mkdir(dir, { recursive: true });
    for (const f of wanted) {
      const target = join(dir, f.name);
      if (existsSync(target) && (f.size === undefined || (await stat(target)).size === f.size)) continue;
      process.stdout.write(`${source.name} ${r.tag}: ${f.name}\n`);
      await fetchTo(f.url, target);
      downloaded++;
    }
    const v = await knownVersionIn(dir, source, r.tag, r.published);
    for (const [variant, fs] of old?.variants ?? []) if (!v.variants.has(variant)) v.variants.set(variant, fs);
    if (old?.boards) v.boards = { ...old.boards, ...v.boards };
    if (v.variants.size > 0) versions.push(v);
  }
  if (versions.length > 0) catalog[source.name] = packKnown(versions.sort((a, b) => b.published.localeCompare(a.published)));
  console.log(`${source.name}: ${versions.map((v) => v.tag).join(', ') || 'nothing'}`);
}

const out = join(import.meta.dirname, '..', 'src', 'core', 'known-files.ts');
const body = `// Generated by scripts/known-files.ts, don't edit by hand.
import type { KnownCatalog } from './known.ts';

export const KNOWN_FILES: KnownCatalog = JSON.parse(${JSON.stringify(JSON.stringify(catalog))});
`;
await writeFile(out, body);
console.log(`${out}: ${(body.length / 1e6).toFixed(1)} MB, ${downloaded} files downloaded`);
